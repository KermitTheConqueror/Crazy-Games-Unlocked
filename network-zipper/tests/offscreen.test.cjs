const {test}=require('node:test');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const path=require('node:path');
const JSZip=require('../lib/jszip.js');
const Zipper=require('../core.js');
test('hidden ZIP builder preserves bytes and releases the download blob',async()=>{
  let listener;
  const records=[{url:'https://cdn.test/asset.wasm',data:Uint8Array.from([0,255,128]),mimeType:'application/wasm',status:200}];
  const context=vm.createContext({chrome:{runtime:{id:'test',onMessage:{addListener:fn=>listener=fn}}},JSZip,Zipper,ZipperDB:{all:async()=>records},URL,Blob,console});
  vm.runInContext(fs.readFileSync(path.join(__dirname,'../offscreen.js'),'utf8'),context);
  const send=message=>new Promise(resolve=>listener({target:'zip-offscreen',...message},{id:'test'},resolve));
  const result=await send({type:'build',state:{gameURL:'https://games.crazygames.com/en_us/test-game/index.html',errors:[]}});
  assert.equal(result.filename,'test-game-network.zip');
  const zip=await JSZip.loadAsync(await (await fetch(result.url)).arrayBuffer());
  assert.deepEqual(await zip.file('files/cdn.test/asset.wasm').async('uint8array'),records[0].data);
  assert.equal(JSON.parse(await zip.file('capture-index.json').async('string')).files.length,1);
  await send({type:'release',url:result.url});
  await assert.rejects(fetch(result.url));
});
